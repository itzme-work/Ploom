import {test,expect} from '@playwright/test'
test('preview, import, select and unlock after a restart',async({page})=>{
 await page.goto('/')
 await page.getByRole('button',{name:'Subscriptions',exact:true}).click()
 await page.getByLabel('Library password').fill('temporary fixture password')
 await page.getByRole('button',{name:'Unlock'}).click()
 await expect(page.getByLabel('Library password')).toHaveCount(0)
 await page.getByLabel('Name',{exact:true}).fill('Fixture')
 await page.getByRole('textbox',{name:'Configurations',exact:true}).fill('trojan://synthetic-password@fixture.invalid:443#Test\nbroken')
 await page.getByRole('button',{name:'Preview',exact:true}).click()
 await expect(page.getByText(/1 valid · 1 invalid/)).toBeVisible()
 await page.getByRole('button',{name:'Import (1)',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Fixture'})).toBeVisible()
 await page.getByRole('button',{name:'Servers',exact:true}).click()
 await page.getByRole('button',{name:'Select',exact:true}).click()
 await expect(page.getByRole('button',{name:'Select',exact:true})).toHaveAttribute('aria-pressed','true')
 await page.reload()
 await page.getByRole('button',{name:'Subscriptions',exact:true}).click()
 await page.getByLabel('Library password').fill('temporary fixture password')
 await page.getByRole('button',{name:'Unlock'}).click()
 await expect(page.getByRole('heading',{name:'Fixture'})).toBeVisible()
 await page.getByRole('button',{name:'Home',exact:true}).click()
 await expect(page.getByText('Fixture · Test · trojan')).toBeVisible()
 expect(await page.evaluate(()=>JSON.stringify(localStorage))).not.toContain('synthetic-password')
})
test('QR image, encrypted backup and explicit restore',async({page},info)=>{
 await page.goto('/')
 await page.getByRole('button',{name:'Subscriptions',exact:true}).click()
 await page.getByLabel('Library password').fill('fixture library password')
 await page.getByRole('button',{name:'Unlock'}).click()
 await expect(page.getByLabel('Library password')).toHaveCount(0)
 await page.getByLabel('File or QR image').setInputFiles('tests/fixtures/subscription-qr.png')
 await expect(page.getByRole('textbox',{name:'Configurations',exact:true})).toHaveValue(/qr.example.invalid/)
 await page.getByLabel('Name',{exact:true}).fill('QR fixture')
 await page.getByRole('button',{name:'Preview',exact:true}).click()
 await page.getByRole('button',{name:'Import (1)',exact:true}).click()
 await expect(page.getByRole('heading',{name:'QR fixture'})).toBeVisible()
 await page.getByText('Backup',{exact:true}).click()
 await page.getByLabel('Backup password (12+ characters)').fill('separate fixture password')
 const file=page.waitForEvent('download')
 await page.getByRole('button',{name:'Save backup'}).click()
 const backup=info.outputPath('backup.json')
 await (await file).saveAs(backup)
 await page.getByText('Details and actions',{exact:true}).click()
 await page.getByRole('button',{name:'Delete',exact:true}).click()
 await page.getByRole('button',{name:'Cancel',exact:true}).click()
 await expect(page.getByRole('heading',{name:'QR fixture'})).toBeVisible()
 await page.getByRole('button',{name:'Delete',exact:true}).click()
 await page.getByRole('button',{name:'Confirm',exact:true}).click()
 await expect(page.getByRole('heading',{name:'QR fixture'})).toHaveCount(0)
 await page.getByLabel('Backup password (12+ characters)').fill('separate fixture password')
 await page.getByLabel('Restore backup').setInputFiles(backup)
 await page.getByRole('button',{name:'Confirm',exact:true}).click()
 await expect(page.getByRole('heading',{name:'QR fixture'})).toBeVisible()
})
